"""Print the /api/lastcall response for a scenario, or write it for the demo page.

    python3 -m lastcall                          # JSON to stdout
    python3 -m lastcall --demo lastcall/demo/data.js
    python3 -m lastcall --scenario path/to/scenario.json
"""

import argparse
import json
import os

from . import core, sim

here = os.path.dirname(os.path.abspath(__file__))
ap = argparse.ArgumentParser(prog="python3 -m lastcall")
field = os.path.join(os.path.dirname(here), "scenario", "field.json")
ap.add_argument("--scenario", default=field if os.path.exists(field) else os.path.join(here, "scenario.json"),
                help="default: scenario/field.json if present, else lastcall/scenario.json")
ap.add_argument("--demo", help="write a data.js file the demo page loads")
args = ap.parse_args()

scenario = core.load_scenario(args.scenario)
result = core.last_call(scenario)

if args.demo:
    # The demo page also draws the tank level for "do nothing" and for the cheapest plan.
    tank = result["shutdown"]["asset_id"] if result.get("shutdown") else None
    best = result["options"][0] if result.get("options") else None
    extra = {}
    if tank:
        plans = {p["id"]: p for p in core.candidate_plans(scenario, [tank])}
        extra["do_nothing_timeline"] = [
            {"t_min": p["t_min"], "level_pct": p["tanks"][tank]}
            for p in sim.forecast(scenario, [], 120, 1)["timeline"]]
        # Tank level if the operator commits to the cheapest plan at minute t, for each whole minute.
        curve = result["curve"]
        level_by_start = {}
        for t in range(0, int(result["shutdown"]["t_min"]) + 1):
            pid = [c for c in curve if c["start_min"] <= t][-1]["plan_id"]
            if pid is None:
                continue
            acts = core.schedule(plans[pid], t)
            level_by_start[t] = [round(p["tanks"][tank], 1) for p in sim.forecast(scenario, acts, 120, 2)["timeline"]]
        extra["level_by_start"] = level_by_start
        extra["level_step_min"] = 2
        extra["shutdown_pct"] = next(t["shutdown_pct"] for t in scenario["tanks"] if t["id"] == tank)
    with open(args.demo, "w") as f:
        f.write("// Generated by `python3 -m lastcall --demo`. Do not edit by hand.\n")
        f.write("window.LASTCALL = " + json.dumps({**result, **extra}, indent=1) + ";\n")
    print(f"wrote {args.demo} ({result['plans_tested']} plans, {result['compute_ms']} ms)")
else:
    print(json.dumps(result, indent=2))
